/**
 * Computes the fitted results that session 2's slides plot, once, and writes
 * them to docs/assets/simulated-fits.js.
 *
 *   node precompute-session2.mjs
 *
 * These could be fitted in the browser, but there is no reason to make every
 * viewer redo the same arithmetic while a slide is loading. Re-run this if the
 * model or the schedules change.
 */

import { writeFile } from 'node:fs/promises';
import {
  makeRng, generateSchedule, generateMagnitudes, simulateRlModel, stableThenVolatile,
} from '../docs/assets/models.js';
import { fitAlphaBeta, fitAlpha, gradientAscent } from '../docs/assets/fitting.js';

const STABLE_P = 0.75;

/** A schedule that holds steady, or one that reverses every 25 trials. */
const blockSchedule = (volatile, n = 100) => (volatile
  ? Array.from({ length: n }, (_, i) => (Math.floor(i / 25) % 2 === 0 ? STABLE_P : 1 - STABLE_P))
  : new Array(n).fill(STABLE_P));

function simulate(alpha, beta, seed, trueProbability = stableThenVolatile()) {
  const rng = makeRng(seed);
  const opt1Rewarded = generateSchedule(trueProbability, rng);
  const magOpt1 = generateMagnitudes(trueProbability.length, rng);
  const magOpt2 = generateMagnitudes(trueProbability.length, rng);
  const { choice1 } = simulateRlModel(opt1Rewarded, magOpt1, magOpt2, alpha, beta, { rng });
  return { opt1Rewarded, magOpt1, magOpt2, choice1 };
}

/* --- parameter recovery --------------------------------------------------- */

console.log('fitting 36 simulated participants for the recovery plots...');
const rng = makeRng(8086);
const RECOVERY = [];
for (let i = 0; i < 36; i++) {
  const alpha = 0.05 + rng() * 0.6;
  const beta = 0.03 + rng() * 0.25;
  const data = simulate(alpha, beta, 1000 + i);
  const fit = fitAlphaBeta(data);
  RECOVERY.push({ alpha, beta, fitAlpha: fit.alpha, fitBeta: fit.beta });
}

/* --- falsification -------------------------------------------------------- */

/**
 * Forty participants per scenario. In one the two blocks share a learning
 * rate, in the other the volatile block gets a higher one. Each block is fitted
 * its own alpha, with beta held at the value it was simulated with.
 */
function blockFits(sameAlpha, seed) {
  const r = makeRng(seed);
  const stable = [], volatile = [];
  for (let i = 0; i < 40; i++) {
    const beta = 0.06 + r() * 0.1;
    const aS = 0.1 + r() * 0.18;
    const aV = sameAlpha ? aS : aS + 0.16 + r() * 0.14;
    stable.push(fitAlpha(simulate(aS, beta, 5000 + i * 2, blockSchedule(false)), beta));
    volatile.push(fitAlpha(simulate(aV, beta, 5001 + i * 2, blockSchedule(true)), beta));
  }
  return { stable, volatile };
}

console.log('fitting both falsification scenarios...');
const FALSIFICATION = { same: blockFits(true, 303), different: blockFits(false, 404) };

/* --- gradient ascent ------------------------------------------------------ */

console.log('walking gradient ascent from two starting points...');
const ascentData = simulate(0.3, 0.2, 4242);
const ASCENT = {
  truth: { alpha: 0.3, beta: 0.2 },
  data: ascentData,
  // Two starting points well away from each other. Neither sits in the very
  // low beta corner, where choices are near random and alpha stops mattering,
  // so the gradient there is mostly numerical noise rather than a real slope.
  paths: [{ alpha: 0.88, beta: 0.085 }, { alpha: 0.05, beta: 0.35 }]
    .map((start) => gradientAscent(ascentData, start)),
};

/* --- write it out --------------------------------------------------------- */

const round = (v, dp = 4) => Number(v.toFixed(dp));
const out = `/* Generated by task-source/precompute-session2.mjs. Do not edit by hand:
   re-run that script instead. It holds the fitted results session 2's slides
   plot, so that no viewer has to refit them while a slide is loading. */

export const RECOVERY = ${JSON.stringify(RECOVERY.map((r) => ({
  alpha: round(r.alpha), beta: round(r.beta),
  fitAlpha: round(r.fitAlpha), fitBeta: round(r.fitBeta),
})))};

export const FALSIFICATION = ${JSON.stringify({
  same: { stable: FALSIFICATION.same.stable.map((v) => round(v, 3)),
          volatile: FALSIFICATION.same.volatile.map((v) => round(v, 3)) },
  different: { stable: FALSIFICATION.different.stable.map((v) => round(v, 3)),
               volatile: FALSIFICATION.different.volatile.map((v) => round(v, 3)) },
})};

export const ASCENT = ${JSON.stringify({
  truth: ASCENT.truth,
  data: {
    opt1Rewarded: Array.from(ASCENT.data.opt1Rewarded),
    magOpt1: Array.from(ASCENT.data.magOpt1),
    magOpt2: Array.from(ASCENT.data.magOpt2),
    choice1: Array.from(ASCENT.data.choice1),
  },
  paths: ASCENT.paths.map((p) => p.map((s) => ({ alpha: round(s.alpha), beta: round(s.beta) }))),
})};
`;

await writeFile('../docs/assets/simulated-fits.js', out);
console.log('wrote docs/assets/simulated-fits.js');
console.log(`  recovery: ${RECOVERY.length} participants`);
console.log(`  falsification: ${FALSIFICATION.same.stable.length} per scenario`);
console.log(`  ascent: ${ASCENT.paths.map((p) => p.length).join(' and ')} steps`);
